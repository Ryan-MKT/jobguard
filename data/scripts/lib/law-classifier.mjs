// ============================================
// 法令類型分類器（改良版，減少「其他」誤判）
// ============================================
//
// 順序由具體到通用，第一個 match 就回傳

const RULES = [
  // 勞動基準法（含相關附屬法規）
  { match: /勞動基準法|勞基法/, type: '勞動基準法' },

  // 性別平等工作法
  { match: /性別平等工作法|性別工作平等法|性平法/, type: '性別平等工作法' },

  // 職業安全衛生法（含許多附屬法規）
  {
    match:
      /職業安全衛生法|職業安全衛生|營造安全衛生|職業安全衛生設施規則|機械設備器具安全|危險性機械|起重升降機|起重機具|高壓氣體|危險物|有害物|缺氧作業|粉塵危害|機械鍋爐壓力容器|職業安全衛生管理|職業健康|噪音管制|防護具|墜落災害|職業病|附屬法規/,
    type: '職業安全衛生法',
  },

  // 勞工退休金條例
  { match: /勞工退休金條例|退休金/, type: '勞工退休金條例' },

  // 就業服務法
  { match: /就業服務法|就服法|招募/, type: '就業服務法' },

  // 中高齡者及高齡者就業促進法
  { match: /中高齡|高齡者就業促進/, type: '中高齡者及高齡者就業促進法' },

  // 勞工職業災害保險及保護法
  { match: /勞工職業災害保險|職災保險|職災保護/, type: '勞工職業災害保險及保護法' },

  // 工會法
  { match: /工會法/, type: '工會法' },

  // 最低工資法
  { match: /最低工資|基本工資/, type: '最低工資法' },

  // 勞工保險條例
  { match: /勞工保險條例/, type: '勞工保險條例' },
];

/**
 * 從「違反法規條款」文字判斷法令類型
 * @param {string} law 例：「勞動基準法第32條第2項」
 * @returns {string}
 */
export function detectLawType(law) {
  if (!law || typeof law !== 'string') return '其他';
  const text = law.trim();
  for (const rule of RULES) {
    if (rule.match.test(text)) return rule.type;
  }
  return '其他';
}
